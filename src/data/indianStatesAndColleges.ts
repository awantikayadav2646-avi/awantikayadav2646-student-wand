export function getCollegesByLocation(
  stateFilter?: string,
  cityFilter?: string
): DirectoryCollege[] {
  const kanpurColleges = getKanpurDirectoryColleges();
  const combined = [
    ...kanpurColleges,
    ...INDIAN_COLLEGES_DIRECTORY.filter((c) => !kanpurColleges.some((kc) => kc.id === c.id)),
  ];

  return combined.filter((college) => {
    const matchesState = !stateFilter || college.state.toLowerCase() === stateFilter.toLowerCase();
    const matchesCity =
      !cityFilter ||
      cityFilter.toLowerCase() === 'all' ||
      college.city.toLowerCase() === cityFilter.toLowerCase() ||
      college.city.toLowerCase().includes(cityFilter.toLowerCase());

    return matchesState && matchesCity;
  });
}

export function searchColleges(
  query: string,
  stateFilter?: string,
  cityFilter?: string
): DirectoryCollege[] {
  const normalizedQuery = query.toLowerCase().trim();
  const kanpurColleges = getKanpurDirectoryColleges();
  const combined = [
    ...kanpurColleges,
    ...INDIAN_COLLEGES_DIRECTORY.filter((c) => !kanpurColleges.some((kc) => kc.id === c.id)),
  ];

  return combined.filter((college) => {
    const matchesState = !stateFilter || college.state.toLowerCase() === stateFilter.toLowerCase();
    if (!matchesState) return false;

    if (cityFilter && cityFilter !== 'All') {
      const matchesCity =
        college.city.toLowerCase() === cityFilter.toLowerCase() ||
        college.city.toLowerCase().includes(cityFilter.toLowerCase());
      if (!matchesCity) return false;
    }

    if (!normalizedQuery) return true;

    return (
      college.name.toLowerCase().includes(normalizedQuery) ||
      college.shortName.toLowerCase().includes(normalizedQuery) ||
      college.city.toLowerCase().includes(normalizedQuery) ||
      college.state.toLowerCase().includes(normalizedQuery) ||
      college.universityAffiliation.toLowerCase().includes(normalizedQuery)
    );
  });
}

